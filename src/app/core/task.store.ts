import { Injectable, signal, computed, effect } from '@angular/core';
/**
 * Store for adding ,updating and delting tasks
 */

export interface Task {
  id: number;
  title: string;
  completed: boolean;
  // priority: 'low' | 'medium' | 'high';
}

@Injectable({
  providedIn: 'root',
})
export class TaskStore {
  private taskSignal = signal<Task[]>(localStorage.getItem('pulse_task') ? JSON.parse(localStorage.getItem('pulse_task')!) : []);//to prevent empty array even if there are tasks in local storage, we initialize the signal with the stored tasks. This way, when the application loads, it will have the existing tasks available immediately without needing to fetch them separately.
  filter = signal<'all' | 'pending' | 'completed'>('all'); 
  tasks = computed(() => this.taskSignal());

  filteredTasks = computed(() => {
    const filterValue = this.filter();
    const tasks = this.taskSignal();// || this.loadFromStorage();
    if (filterValue === 'pending') {
      return tasks.filter(task => !task.completed);
    } else if (filterValue === 'completed') {
      return tasks.filter(task => task.completed);
    }
    return tasks;
  });
  //to show how much tasks are completed
  public completionPercentage = computed(() => {
    const tasks = this.taskSignal();
    if (tasks.length === 0) return 0;
    const completedTasks = tasks.filter(task => task.completed).length;
    return ((completedTasks / tasks.length) * 100).toFixed(1);
  });
  //persistent sync
  constructor(){
    effect(() => {
      localStorage.setItem('pulse_task',JSON.stringify(this.taskSignal()));
    })
  }
  //add tasks
  addTask(title: string) {
    this.taskSignal.update(tasks => [...tasks, {id:Date.now(),title,completed:false}]);
  }
  //to toggle tasks to completed
  toggleTask(id: number) {
    this.taskSignal.update(tasks => tasks.map(t => t.id === id ? { ...t, completed: !t.completed } : t)
    );
  }
  //delete tasks
  deleteTask(id: number) {
    this.taskSignal.update(tasks => tasks.filter(t => t.id !== id));
  }

  private loadFromStorage(): Task[] {
    const saved = localStorage.getItem('pulse_task');
    console.log('Loaded tasks from storage:', saved);
    return saved ? JSON.parse(saved) : [];
  }




































































































































































































































































































































































































   




























   







   









































































































































































































































































  











  




  
  
















































































































































































































































































































































































}
